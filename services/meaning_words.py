# Варианты для каждой буквы: первый — основной, остальные — популярные альтернативы
_RU = {
    "а": ["a"], "б": ["b"], "в": ["v"], "г": ["g"], "д": ["d"], "е": ["e"], "ё": ["yo", "e"],
    "ж": ["zh", "j"], "з": ["z"], "и": ["i"], "й": ["y", "i"], "к": ["k"], "л": ["l"], "м": ["m"],
    "н": ["n"], "о": ["o"], "п": ["p"], "р": ["r"], "с": ["s"], "т": ["t"], "у": ["u"], "ф": ["f"],
    "х": ["kh", "h"], "ц": ["ts", "c"], "ч": ["ch"], "ш": ["sh"], "щ": ["sch", "sh"], "ъ": [""],
    "ы": ["y", "i"], "ь": [""], "э": ["e"], "ю": ["yu", "iu"], "я": ["ya", "ia"],
}
_UA = {
    **_RU, "г": ["h", "g"], "ґ": ["g"], "е": ["e"], "є": ["ye", "ie"], "и": ["y", "i"], "і": ["i"],
    "ї": ["yi", "i"], "щ": ["shch", "sch"], "'": [""], "’": [""],
}
_KZ = {
    **_RU, "ә": ["a", "ae"], "ғ": ["g", "gh"], "қ": ["q", "k"], "ң": ["ng", "n"], "ө": ["o", "oe"],
    "ұ": ["u"], "ү": ["u", "ue"], "һ": ["h"], "і": ["i"], "у": ["u", "w"], "ы": ["y", "i"],
}
_TABLES = {"ru": _RU, "ua": _UA, "kz": _KZ}
_VALID = re.compile(r"^[a-z][a-z0-9_]{3,31}$")
MAX_VARIANTS = 4


def translit(word: str, lang: str) -> list[str]:
    """Варианты написания латиницей, основной — первым. Для английского — само слово."""
    if lang == "en":
        return [word]
    table = _TABLES[lang]
    parts = [table.get(ch, [ch]) for ch in word.lower()]
    variants: list[str] = []
    for combo in product(*parts):
        v = "".join(combo)
        if v not in variants:
            variants.append(v)
        if len(variants) >= MAX_VARIANTS:
            break
    return variants


@dataclass(frozen=True)
class Candidate:
    username: str
    word: str  # исходное слово (для украинского и казахского — кириллицей)
    meaning: str  # перевод, если есть
    lang: str


def _entries(lang: str, theme: str) -> list[tuple[str, str]]:
    out = []
    for item in _WORDS[lang][theme].split():
        word, _, meaning = item.partition(":")
        out.append((word, meaning.replace("_", " ")))
    return out


def candidates(lang: str, theme: str, length: int) -> list[Candidate]:
    """Перемешанные варианты для выбора. lang/theme — ключ или "any", length — 5..8 или 0 (любая)."""
    langs = list(LANGS) if lang == "any" else [lang]
    themes = list(THEMES) if theme == "any" else [theme]
    out: list[Candidate] = []
    seen: set[str] = set()
    for lg in langs:
        for th in themes:
            for word, meaning in _entries(lg, th):
                for name in translit(word, lg):
                    if name in seen or not _VALID.match(name) or len(name) < 5:
                        continue
                    if length and len(name) != length:
                        continue
                    seen.add(name)
                    out.append(Candidate(name, word, meaning, lg))
    random.shuffle(out)
    return out


def describe(lang: str, theme: str, length: int) -> str:
    lang_t = "🌍 Любой язык" if lang == "any" else " ".join(LANGS[lang])
    theme_t = "🎲 Любая тема" if theme == "any" else " ".join(THEMES[theme])
    len_t = "любая длина" if not length else f"{length} букв"
    return f"{lang_t} · {theme_t} · {len_t}"


def label(c: Candidate) -> str:
    """Подпись к нику: исходное слово и/или перевод."""
    if c.lang == "en":
        return c.meaning
    if c.meaning:
        return f"{c.word} — {c.meaning}"
    return c.word
